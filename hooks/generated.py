#!/usr/bin/env python3
"""Decide whether a file is generated, vendored or build output.

Both hooks skip these paths: the rules apply to code a person writes, and a
generator's output is regenerated, not refactored.

Add project-specific patterns with CLAUDE_GENERATED_EXTRA, a comma-separated
list of regular expressions matched against the path.
"""
import os
import re

VENDOR_DIRECTORY = re.compile(
    r"(^|/)(node_modules|bower_components|vendor|third_party|\.venv|venv"
    r"|__pycache__|\.mypy_cache|\.pytest_cache|\.tox|\.next|\.nuxt|\.svelte-kit"
    r"|\.output|\.turbo|dist|build|out|target|coverage|site-packages)/"
)

GENERATED_DIRECTORY = re.compile(
    r"(^|/)(__generated__|generated|_generated|gen|codegen|autogen|auto_generated"
    r"|migrations|proto|protos|graphql/types|api/generated|openapi)/",
    re.IGNORECASE,
)

GENERATED_FILE = re.compile(
    r"\.(gen|generated|g)\.[a-z]+$"
    r"|\.d\.ts$"
    r"|(^|/)(openapi|swagger)[^/]*\.(json|ya?ml|ts|js)$"
    r"|(^|/)schema\.(graphql|gql|json)$"
    r"|_pb2(_grpc)?\.pyi?$"
    r"|_pb\.[jt]s$"
    r"|\.pb\.(go|ts|js)$"
    r"|(^|/)(package-lock|yarn|pnpm-lock|bun|composer|poetry|Cargo)\.(json|lock|ya?ml)$"
    r"|\.min\.(js|css)$",
    re.IGNORECASE,
)

HEADER_MARKER = re.compile(
    r"@generated"
    r"|generated by"
    r"|code generated"
    r"|auto[- ]?generated"
    r"|automatically generated"
    r"|do not edit"
    r"|don't edit",
    re.IGNORECASE,
)

HEADER_BYTES = 4096


def extra_patterns():
    raw = os.environ.get("CLAUDE_GENERATED_EXTRA", "")
    return [re.compile(piece.strip()) for piece in raw.split(",") if piece.strip()]


def has_generated_header(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            return bool(HEADER_MARKER.search(handle.read(HEADER_BYTES)))
    except OSError:
        return False


def is_generated(path):
    normalised = path.replace("\\", "/")
    if VENDOR_DIRECTORY.search(normalised):
        return True
    if GENERATED_DIRECTORY.search(normalised):
        return True
    if GENERATED_FILE.search(normalised):
        return True
    if any(pattern.search(normalised) for pattern in extra_patterns()):
        return True
    return has_generated_header(path)
